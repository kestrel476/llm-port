"""Ошибки провайдеров, разделённые по тому, что с ними делать.

Это не украшательство иерархии, а исправление конкретного дефекта. Существующий
фолбэк перехватывает ЛЮБОЕ исключение и молча переключается на запасную модель:

    except Exception as exc:
        last_error = exc
        ...  # пробуем следующего кандидата

В результате неверный ключ, недоступный эндпоинт и опечатка в имени модели выглядят
для сервиса ровно так же, как обрыв соединения: запрос отрабатывает на запасной
модели, никто ничего не замечает, а качество тихо падает. На замерах это проявилось
как 2% «необъяснимых» расхождений — и объяснились они только тогда, когда стало
понятно, что часть запросов уходила не на ту модель.

Правило простое:

- `TransientError` — имеет смысл повторить и есть смысл идти к запасному кандидату;
- `FatalError` — повторять бессмысленно, к запасному идти ОПАСНО: он выполнит запрос,
  и ошибка конфигурации останется незамеченной.
"""

from __future__ import annotations


class LLMError(Exception):
    """Базовая ошибка обращения к модели."""

    def __init__(self, message: str, *, provider: str = "", model: str = "") -> None:
        super().__init__(message)
        self.provider = provider
        self.model = model

    def __str__(self) -> str:
        where = " ".join(part for part in (self.provider, self.model) if part)
        return f"{super().__str__()} [{where}]" if where else super().__str__()


# ── временные: повторять можно ───────────────────────────────────────────────


class TransientError(LLMError):
    """Временная неполадка: сеть, перегрузка, таймаут."""


class RequestTimeoutError(TransientError):
    """Провайдер не ответил за отведённое время."""


class TransportError(TransientError):
    """Соединение не установлено или оборвалось.

    Сюда же попадает обрыв уже начатого ответа. Он коварен тем, что на уровне HTTP
    выглядит успехом: статус 200 получен, а тело недочитано.
    """


class RateLimitedError(TransientError):
    """Превышен лимит запросов.

    `retry_after_s` заполняется, если провайдер сообщил, сколько ждать: спать
    вслепую с экспоненциальной задержкой хуже, чем послушаться заголовка.
    """

    def __init__(self, message: str, *, retry_after_s: float | None = None, **kwargs: str) -> None:
        super().__init__(message, **kwargs)
        self.retry_after_s = retry_after_s


class ServerError(TransientError):
    """Провайдер вернул 5xx."""


# ── постоянные: повторять бессмысленно ───────────────────────────────────────


class FatalError(LLMError):
    """Ошибка, которая сама не пройдёт: повтор и фолбэк её только замаскируют."""


class AuthError(FatalError):
    """Ключ неверен, истёк или не имеет доступа."""


class BadRequestError(FatalError):
    """Запрос не принят провайдером.

    Типичный случай: поле, которого этот эндпоинт не поддерживает. Например, попытка
    отключить reasoning там, где он обязателен, — ответ 400 «Reasoning is mandatory».
    Уводить такой запрос на запасную модель нельзя: там он, возможно, пройдёт, и
    несовместимость конфигурации останется незамеченной.
    """


class ModelNotFoundError(FatalError):
    """Модели с таким именем у провайдера нет."""


class ContentFilteredError(FatalError):
    """Запрос или ответ отклонён фильтром провайдера.

    Формально не ошибка конфигурации, но повторять и уводить на другую модель тоже
    не следует: причина в содержании, а не в канале.
    """


class MalformedResponseError(LLMError):
    """Ответ получен, но разобрать его не удалось.

    Намеренно не отнесён ни к временным, ни к постоянным: причина бывает разной —
    от обрыва тела (лечится повтором) до несовместимости формата (не лечится).
    Решение принимает политика, а не тип исключения.
    """
